// Precomputes the globe's dotted-continent points so the browser doesn't have to.
// Samples a Fibonacci sphere and keeps points that fall on land (Natural Earth 110m).
// Run: node scripts/build-land-dots.mjs  → writes src/data/landDots.js
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)
const feats = land.features || [land]

// Flatten to polygons (arrays of rings) with bounding boxes for a fast reject.
const polys = []
for (const f of feats) {
  const list = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  for (const rings of list) {
    let minX = 180, maxX = -180, minY = 90, maxY = -90
    for (const [x, y] of rings[0]) {
      if (x < minX) minX = x
      if (x > maxX) maxX = x
      if (y < minY) minY = y
      if (y > maxY) maxY = y
    }
    polys.push({ rings, minX, maxX, minY, maxY })
  }
}

// Even-odd ray casting across all rings (holes cancel out), same as the old canvas raster.
const inside = (lon, lat) => {
  let hit = false
  for (const p of polys) {
    if (lon < p.minX || lon > p.maxX || lat < p.minY || lat > p.maxY) continue
    for (const ring of p.rings) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i]
        const [xj, yj] = ring[j]
        if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
      }
    }
  }
  return hit
}

const COUNT = 16000
const golden = Math.PI * (3 - Math.sqrt(5))
const out = []
for (let i = 0; i < COUNT; i++) {
  const y = 1 - (i / (COUNT - 1)) * 2
  const lat = (Math.asin(y) * 180) / Math.PI
  if (lat < -58) continue
  const lon = ((((golden * i * 180) / Math.PI) % 360) + 360) % 360 - 180
  if (inside(lon, lat)) out.push(Math.round(lat * 10), Math.round(lon * 10))
}

writeFileSync(
  new URL('../src/data/landDots.js', import.meta.url),
  `// Generated by scripts/build-land-dots.mjs — lat/lon pairs in tenths of a degree.\nexport default '${out.join(',')}'\n`
)
console.log(`wrote ${out.length / 2} land dots`)
